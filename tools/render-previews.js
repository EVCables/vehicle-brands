#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { COLOUR_MODES, MARK_TYPES } from './config.js';
import { ensureDir, readJson } from './lib.js';

const approvals = readJson('qa/visual-approvals.json');
const records = new Map(approvals.records.map((record) => [record.asset, record]));
const brands = readJson('data/brands.json');
const outDir = 'qa/previews';
ensureDir(outDir);

const cards = [];
for (const brand of brands) {
  for (const mark of MARK_TYPES) {
    for (const mode of COLOUR_MODES) {
      const file = path.join('src', brand.slug, mark, `${mode}.svg`);
      if (!fs.existsSync(file)) continue;
      const key = `${brand.slug}/${mark}/${mode}`;
      const svg = fs.readFileSync(file, 'utf8');
      const encoded = Buffer.from(svg).toString('base64');
      const record = records.get(key);
      cards.push({ key, status: record?.status || 'missing-qa-record', notes: record?.notes || '', dataUri: `data:image/svg+xml;base64,${encoded}` });
    }
  }
}

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>Vehicle brand SVG visual QA previews</title>
  <style>
    body { font-family: system-ui, sans-serif; margin: 24px; background: #f5f5f5; color: #111; }
    .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(280px, 1fr)); gap: 16px; }
    .card { background: white; border: 1px solid #ddd; border-radius: 8px; padding: 12px; }
    .stage { height: 180px; display: grid; grid-template-columns: 1fr 1fr; gap: 8px; }
    .swatch { display: flex; align-items: center; justify-content: center; border: 1px solid #ddd; overflow: hidden; }
    .swatch.dark { background: #111; }
    img { max-width: 92%; max-height: 92%; }
    code { font-size: 12px; }
    .status { display: inline-block; margin-top: 8px; padding: 2px 6px; border-radius: 999px; background: #eee; }
    .approved { background: #d9fbe5; }
    .review-fallback { background: #fff1c7; }
    .blocked { background: #ffd7d7; }
  </style>
</head>
<body>
  <h1>Vehicle brand SVG visual QA previews</h1>
  <p>Generated by <code>npm run preview</code>. Review each asset against official references before marking it approved in <code>qa/visual-approvals.json</code>.</p>
  <div class="grid">
    ${cards.map((card) => `<section class="card">
      <h2><code>${escapeHtml(card.key)}</code></h2>
      <div class="stage">
        <div class="swatch"><img src="${card.dataUri}" alt="${escapeHtml(card.key)} on white" /></div>
        <div class="swatch dark"><img src="${card.dataUri}" alt="${escapeHtml(card.key)} on dark" /></div>
      </div>
      <div class="status ${escapeHtml(card.status)}">${escapeHtml(card.status)}</div>
      <p>${escapeHtml(card.notes)}</p>
    </section>`).join('\n')}
  </div>
</body>
</html>
`;

fs.writeFileSync(path.join(outDir, 'index.html'), html);
console.log(`wrote ${path.join(outDir, 'index.html')} with ${cards.length} asset previews`);

function escapeHtml(value) {
  return String(value).replace(/[&<>"]/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[char]));
}
